"""Turns a run into REPORT.md, the README results block, and the gate verdict. Reports are generated, never edited."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

ORDER = ("status_quo", "desk", "checks_late", "no_skill_match", "no_agent", "no_early_warning")
START, END = "<!-- results:start -->", "<!-- results:end -->"


def gate(doc: dict[str, Any], gates: dict[str, Any]) -> list[tuple[str, bool, str]]:
    """Every gate the desk must pass, with what was measured."""
    g, d, sq = gates["desk"], doc["designs"]["desk"], doc["designs"]["status_quo"]
    wrong_cap = g["wrongAnswersPer1000MaxShareOfStatusQuo"] * sq["wrong_answers_per_1000"][0]
    return [
        (
            f"weeks saved, low end of the interval, at least {g['weeksSavedLowMin']}",
            d["weeks_saved_vs_status_quo"][1] >= g["weeksSavedLowMin"],
            f"{d['weeks_saved_vs_status_quo'][1]:.2f}",
        ),
        (f"on-time share at least {g['onTimeShareMin']:.0%}", d["on_time_share"][0] >= g["onTimeShareMin"], f"{d['on_time_share'][0]:.0%}"),
        (f"P1 incidents per 10 go-lives at most {g['p1Per10Max']}", d["p1_per_10_golives"][0] <= g["p1Per10Max"], f"{d['p1_per_10_golives'][0]:.2f}"),
        (
            f"documents exposed per 10 go-lives at most {g['exposurePer10Max']:g}",
            d["exposure_per_10_golives"][0] <= g["exposurePer10Max"],
            f"{d['exposure_per_10_golives'][0]:.2f}",
        ),
        (
            f"wrong questionnaire answers per 1,000 at most {g['wrongAnswersPer1000MaxShareOfStatusQuo']:.0%} of today's",
            d["wrong_answers_per_1000"][0] <= wrong_cap,
            f"{d['wrong_answers_per_1000'][0]:.1f} (cap {wrong_cap:.1f})",
        ),
        (f"blocker findings no planted problem explains at most {g['falseAlarmsMax']}", doc["facts"]["false_alarms"] <= g["falseAlarmsMax"], str(doc["facts"]["false_alarms"])),
    ]


def _ci(v: list[float], fmt: str) -> str:
    return f"{v[0]:{fmt}} ({v[1]:{fmt}}–{v[2]:{fmt}})"


def headline(doc: dict[str, Any]) -> str:
    d, sq, f = doc["designs"]["desk"], doc["designs"]["status_quo"], doc["facts"]
    s = d["weeks_saved_vs_status_quo"]
    return (
        f"On {len(doc['seeds'])} {'held-out' if doc['set'] == 'heldout' else 'development'} seeds ({f['customers']} simulated customers), the desk took customers live in "
        f"{d['weeks_to_golive'][0]:.1f} weeks against {sq['weeks_to_golive'][0]:.1f} today: {s[0]:.1f} weeks sooner "
        f"(95% interval {s[1]:.1f}–{s[2]:.1f}), {d['on_time_share'][0]:.0%} on the committed date against "
        f"{sq['on_time_share'][0]:.0%}, and {d['p1_per_10_golives'][0]:.1f} P1 incidents per 10 go-lives against "
        f"{sq['p1_per_10_golives'][0]:.1f}."
    )


def tables(doc: dict[str, Any]) -> str:
    ds = doc["designs"]
    rows = [
        "| Design | Weeks to go-live | On time | P1 per 10 go-lives | Exposures per 10 | Wrong answers per 1,000 | Security turnaround (weeks) | Weeks saved vs today |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for n in ORDER:
        d = ds[n]
        saved = "–" if n == "status_quo" else _ci(d["weeks_saved_vs_status_quo"], ".1f")
        rows.append(
            f"| {d['label']} | {_ci(d['weeks_to_golive'], '.1f')} | {d['on_time_share'][0]:.0%} | "
            f"{d['p1_per_10_golives'][0]:.2f} | {d['exposure_per_10_golives'][0]:.2f} | "
            f"{d['wrong_answers_per_1000'][0]:.1f} | {d['security_turnaround_weeks'][0]:.1f} | {saved} |"
        )
    team = [
        "| Design | Revenue live inside the horizon, per seed | Manager-weeks over capacity | Lead hours per week stepping in |",
        "|---|---|---|---|",
    ]
    for n in ORDER:
        d = ds[n]
        team.append(f"| {d['label']} | ${d['revenue_in_horizon_per_seed'] / 1e6:.2f}M | {d['overload_share']:.0%} | {d['lead_hours_per_week']:.1f} |")
    f = doc["facts"]
    facts = (
        f"Planted setup problems: {f['planted_problems']}; found by the kickoff checks: {f['found_at_kickoff']}; "
        f"blocker findings no planted problem explains: {f['false_alarms']}; questionnaire questions: {f['questions']:,}."
    )
    return "\n".join(rows) + "\n\n" + "\n".join(team) + "\n\n" + facts


def block(dev: dict[str, Any], heldout: dict[str, Any] | None, gates: dict[str, Any]) -> str:
    parts = [START, "", "_Generated by `python -m golive.eval.cli readme` from `reports/`. Do not edit by hand._", ""]
    for doc in (heldout, dev):
        if doc is None:
            continue
        verdict = gate(doc, gates)
        ok = all(p for _, p, _ in verdict)
        parts += [
            f"### {'Held-out' if doc['set'] == 'heldout' else 'Development'} seeds {doc['seeds']} · config `{doc['config_sha']}` · gates {'pass' if ok else 'FAIL'}",
            "",
            headline(doc),
            "",
            tables(doc),
            "",
        ]
    if heldout is None:
        parts += ["_The held-out seeds have not been run yet._", ""]
    parts.append(END)
    return "\n".join(parts)


def write_readme(readme: Path, text: str) -> bool:
    old = readme.read_text()
    new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: text, old, flags=re.S)
    if new != old:
        readme.write_text(new)
    return new != old


def report_md(dev: dict[str, Any], heldout: dict[str, Any] | None, gates: dict[str, Any]) -> str:
    lines = ["# Results", "", "_Generated from `reports/`. Do not edit by hand._", ""]
    for doc in (heldout, dev):
        if doc is None:
            continue
        lines += [f"## {doc['set']} seeds {doc['seeds']} (config `{doc['config_sha']}`)", "", headline(doc), "", tables(doc), "", "| Gate | Measured | Pass |", "|---|---|---|"]
        lines += [f"| {name} | {measured} | {'yes' if ok else 'NO'} |" for name, ok, measured in gate(doc, gates)]
        lines.append("")
    return "\n".join(lines)
